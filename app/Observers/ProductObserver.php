    }

    /**
     * Handle the Product "updated" event.
     */
    public function updated(Product $product): void
    {
        if ($product->wasChanged('is_active') && $product->is_active) {
            SendProductAvailableToSubscribersJob::dispatch($product->id)->afterCommit();
        }
    }

